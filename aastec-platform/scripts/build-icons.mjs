// ===================================================================
//  Builds public/img/icons.svg — a sprite of the Lucide icons (ISC licence)
//  used by the portal. Run `npm run icons` after adding a name below.
// ===================================================================
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = process.argv[2] || join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const OUT = join(__dirname, '..', 'public', 'img', 'icons.svg');

const ICONS = `
layout-dashboard users user user-plus user-check user-cog user-x users-round network building-2 building landmark school
calendar calendar-days calendar-plus calendar-check calendar-clock vote square-check clipboard-check clipboard-list file-text
file-chart-column file-check file-plus file-pen-line book-open book-open-check graduation-cap brain brain-circuit sparkles bot
rocket lightbulb handshake trophy award medal shield-check shield shield-alert scale gavel message-square message-circle
messages-square mail bell search settings log-out log-in chevron-down chevron-right chevron-left chevron-up arrow-right arrow-left
arrow-up-right plus minus x check circle-check circle-check-big circle-x circle-alert triangle-alert info eye eye-off pencil
trash-2 download upload printer share-2 heart thumbs-up bookmark flag image chart-column chart-pie chart-line chart-no-axes-combined
trending-up trending-down clock map-pin globe link qr-code scan-line key-round lock lock-open history scroll-text list-checks
list filter refresh-cw menu sun moon circle-help target activity zap flame star briefcase layers git-branch workflow send
paperclip smile megaphone presentation hash at-sign circle-dot gauge radar folder inbox crown badge-check wallet ticket
video circle-play timer sliders-horizontal external-link copy house compass sprout boxes archive stamp list-todo ban
octagon-alert map party-popper heart-handshake mic user-round-check circle-user-round funnel coffee sprout chart-bar
square-pen calendar-range building-2 notebook-pen circle-plus circle-minus thumbs-down laugh hand-heart reply repeat-2 at-sign
`.trim().split(/\s+/);

if (!existsSync(SRC)) { console.error('lucide-static icons not found at', SRC, '— run npm install first'); process.exit(1); }
const seen = new Set(); const symbols = []; const missing = [];
for (const name of ICONS) {
  if (seen.has(name)) continue; seen.add(name);
  const file = join(SRC, name + '.svg');
  if (!existsSync(file)) { missing.push(name); continue; }
  const svg = readFileSync(file, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`);
}
writeFileSync(OUT, `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><!-- Lucide icons (ISC) — generated by scripts/build-icons.mjs -->\n${symbols.join('\n')}\n</svg>\n`);
console.log(`icons.svg: ${symbols.length} icons` + (missing.length ? ` — missing: ${missing.join(', ')}` : ''));
